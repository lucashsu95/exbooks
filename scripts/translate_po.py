def fill_korean():
    """Translate Chinese msgid to Korean msgstr."""
    po = polib.pofile(KO_PO)
    count = 0
    skipped = 0
    for entry in po:
        if not entry.msgid:
            continue
        if entry.msgstr and entry.msgstr != entry.msgid:
            skipped += 1
            continue
        translation = translate_chinese_to_korean(entry.msgid)
        entry.msgstr = translation
        count += 1
    po.save()
    print(f"ko: translated {count} strings ({skipped} already had translations)")


