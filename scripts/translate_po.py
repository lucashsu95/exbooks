def fill_zh_hant():
    """zh_Hant: copy msgid to msgstr (source is already Chinese)."""
    po = polib.pofile(ZH_HANT_PO)
    count = 0
    for entry in po:
        if entry.msgid and not entry.msgstr:
            entry.msgstr = entry.msgid
            count += 1
    po.save()
    print(f"zh_Hant: filled {count} translations")


